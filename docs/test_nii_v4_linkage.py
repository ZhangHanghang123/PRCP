SRC = 'v2/NII计量模版_v4_逐月利息推演.xlsx'
TMP = '_v4_link.xlsx'


def run(title, mutate, probes):
    shutil.copyfile(SRC, TMP)
    wb = openpyxl.load_workbook(TMP)
    mutate(wb)
    wb.save(TMP)
    exc = ExcelCompiler(filename=TMP)
    res = {}
    for lab, sh, cell in probes:
        try:
            res[lab] = exc.evaluate(f"'{sh}'!{cell}")
        except Exception as e:
            res[lab] = f'ERR:{type(e).__name__}'
    os.remove(TMP)
    print(f'— {title} —')
    for lab in res:
        v = res[lab]
        print(f'    {lab:<30} = {v if not isinstance(v, float) else format(v, ",.6f")}')
    return res


def V(sh, cell):
    exc = ExcelCompiler(filename=SRC)
